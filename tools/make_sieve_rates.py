"""Generate kubejs/server_scripts/sieve_rates.js: SkyOrigins 2's sieve drop rates.

Reads Ex Deorum's own sieve recipes from its jar (pack-mods/exdeorum-*.jar), raises the metal drops the
pack depends on to at least the minimums below (never lowers one), and adds sieve drops for materials
Ex Deorum doesn't cover. Edit the tables here and rerun; don't edit the generated script by hand:

    python tools/make_sieve_rates.py

Rates are per sieve use with each mesh: string, flint, iron, golden, diamond, netherite.
"""

import glob
import json
import os
import re
import zipfile

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "kubejs", "server_scripts", "sieve_rates.js")
MESHES = ["string", "flint", "iron", "golden", "diamond", "netherite"]

# SkyOrigins 1 sieved too little metal, so these are floors under Ex Deorum's rates.
# 4 ore chunks make 1 ore, so a 0.16 chance is ~25 gravel per ore with a String Mesh.
PRIMARY = [0.16, 0.18, 0.20, 0.22, 0.25, 0.28]    # metals needed in bulk
SECONDARY = [0.10, 0.11, 0.13, 0.15, 0.17, 0.20]  # metals needed in smaller amounts
DEEPSLATE_BONUS = 1.2                               # crushed deepslate is a later, harder input

# Ex Deorum result -> (floor, mods that add the ore; empty = vanilla, always present)
FLOORS = {
    "iron_ore_chunk": (PRIMARY, []),
    "copper_ore_chunk": (PRIMARY, []),
    "osmium_ore_chunk": (PRIMARY, ["mekanism"]),
    "tin_ore_chunk": (PRIMARY, ["mekanism", "thermal"]),
    "gold_ore_chunk": (SECONDARY, []),
    "lead_ore_chunk": (SECONDARY, ["mekanism", "thermal"]),
    "silver_ore_chunk": (SECONDARY, ["thermal", "occultism"]),
    "nickel_ore_chunk": (SECONDARY, ["thermal"]),
    "zinc_ore_chunk": (SECONDARY, ["create"]),
    "uranium_ore_chunk": (SECONDARY, ["mekanism"]),
    "redstone": (SECONDARY, []),  # Mekanism infusing eats redstone
}

# Drops Ex Deorum has no sieve recipe for: (mod, item, input block, rates)
NEW_DROPS = [
    ("mekanism", "mekanism:fluorite_gem", "minecraft:gravel", [0.03, 0.04, 0.05, 0.06, 0.07, 0.08]),
    ("mekanism", "mekanism:fluorite_gem", "exdeorum:crushed_deepslate", [0.06, 0.07, 0.08, 0.10, 0.12, 0.14]),
    ("thermal", "thermal:apatite", "minecraft:gravel", [0.06, 0.07, 0.08, 0.09, 0.10, 0.12]),
    ("thermal", "thermal:cinnabar", "exdeorum:crushed_netherrack", [0.05, 0.06, 0.07, 0.08, 0.10, 0.12]),
    ("thermal", "thermal:niter", "minecraft:sand", [0.06, 0.07, 0.08, 0.09, 0.10, 0.12]),
    ("thermal", "thermal:sulfur", "exdeorum:crushed_netherrack", [0.08, 0.09, 0.10, 0.12, 0.14, 0.16]),
    ("mysticalagriculture", "mysticalagriculture:inferium_essence", "minecraft:dirt", [0.05, 0.06, 0.07, 0.08, 0.10, 0.12]),
    ("mysticalagriculture", "mysticalagriculture:prosperity_shard", "minecraft:gravel", [0.03, 0.04, 0.05, 0.06, 0.07, 0.08]),
]


def ex_deorum_recipes():
    jar = glob.glob(os.path.join(ROOT, "pack-mods", "exdeorum-*.jar"))[0]
    with zipfile.ZipFile(jar) as z:
        for name in z.namelist():
            m = re.match(r"data/exdeorum/recipes/(sieve/([a-z_]+)/([a-z_]+)/([a-z_]+))\.json", name)
            if not m or m.group(4) not in FLOORS:
                continue
            recipe = json.loads(z.read(name))
            if recipe["type"] == "forge:conditional":
                recipe = recipe["recipes"][0]["recipe"]
            yield "exdeorum:" + m.group(1), m.group(2), m.group(3), m.group(4), recipe


def main():
    boosts, kept = [], 0
    for rid, block, mesh, result, recipe in sorted(ex_deorum_recipes()):
        amount = recipe["result_amount"]
        if not isinstance(amount, dict) or amount.get("type") != "minecraft:binomial":
            kept += 1
            continue
        floor, mods = FLOORS[result]
        target = floor[MESHES.index(mesh)] * (DEEPSLATE_BONUS if block == "crushed_deepslate" else 1)
        n, p = amount["n"], amount["p"]
        new_p = round(max(p, target / n), 3)
        if new_p <= p:
            kept += 1
            continue
        boosts.append({"id": rid, "mods": mods, "ingredient": recipe["ingredient"], "mesh": recipe["mesh"],
                       "result": recipe["result"], "n": n, "old": p, "p": new_p})

    added = []
    for mod, item, block, rates in NEW_DROPS:
        for mesh, p in zip(MESHES, rates):
            added.append({"mods": [mod], "ingredient": {"item": block}, "mesh": f"exdeorum:{mesh}_mesh",
                          "result": item, "n": 1.0, "p": p,
                          "id": f"skyorigins2core:sieve/{block.split(':')[1]}/{mesh}/{item.split(':')[1]}"})

    lines = [
        "// GENERATED by tools/make_sieve_rates.py - edit the tables there and rerun, not this file.",
        "// SkyOrigins 2 sieve rates: raises Ex Deorum's metal (and redstone) drops to the pack's minimums and adds",
        "// drops Ex Deorum lacks. Each entry only applies when one of its mods is installed (empty = always).",
        f"// {len(boosts)} recipes raised, {kept} already at or above the minimum, {len(added)} drops added.",
        "",
        "const SIEVE_BOOSTS = [",
    ]
    for b in boosts:
        lines.append(f"    // {b['id']}: {b['old']} -> {b['p']}")
        lines.append("    " + json.dumps({k: b[k] for k in ("id", "mods", "ingredient", "mesh", "result", "n", "p")}) + ",")
    lines += ["]", "", "const SIEVE_ADDITIONS = ["]
    for a in added:
        lines.append("    " + json.dumps({k: a[k] for k in ("id", "mods", "ingredient", "mesh", "result", "n", "p")}) + ",")
    lines += [
        "]",
        "",
        "ServerEvents.recipes(event => {",
        "    const present = mods => mods.length == 0 || mods.some(mod => Platform.isLoaded(mod))",
        "    const sieve = e => event.custom({",
        "        type: 'exdeorum:sieve',",
        "        ingredient: e.ingredient,",
        "        mesh: e.mesh,",
        "        result: e.result,",
        "        result_amount: { type: 'minecraft:binomial', n: e.n, p: e.p },",
        "    })",
        "    SIEVE_BOOSTS.filter(e => present(e.mods)).forEach(e => {",
        "        event.remove({ id: e.id })",
        "        sieve(e).id(e.id.replace('exdeorum:', 'skyorigins2core:'))",
        "    })",
        "    SIEVE_ADDITIONS.filter(e => present(e.mods)).forEach(e => sieve(e).id(e.id))",
        "})",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(boosts)} raised, {kept} kept, {len(added)} added -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
